#!/usr/bin/env node
/**
 * Regenerates src/infrastructure/nlp/concreteness.data.ts from Brysbaert,
 * Warriner & Kuperman (2014), "Concreteness ratings for 40 thousand generally
 * known English word lemmas", Behavior Research Methods. CC-BY 4.0.
 *
 *   node scripts/build-concreteness.mjs [--min-freq 20]
 *
 * Keeps single-word lemmas known to ≥90% of raters with SUBTLEX frequency
 * ≥ min-freq. Encodes each as `word` + score×10 (two digits), space-separated.
 */
import { readFileSync, writeFileSync } from "node:fs";

const flag = process.argv.indexOf("--min-freq");
const minFreq = flag === -1 ? 20 : Number(process.argv[flag + 1]);
const lines = readFileSync("data/Concreteness_ratings_Brysbaert_et_al_BRM.txt", "utf8").trim().split("\n");
const header = lines.shift().split("\t");
const col = (name) => header.indexOf(name);
const [W, B, C, K, F] = ["Word", "Bigram", "Conc.M", "Percent_known", "SUBTLEX"].map(col);

const entries = [];
for (const line of lines) {
  const f = line.split("\t");
  if (f[B] !== "0" || !/^[a-z]{3,}$/.test(f[W])) continue;
  if (Number(f[K]) < 0.9 || Number(f[F]) < minFreq) continue;
  entries.push(`${f[W]}${String(Math.round(Number(f[C]) * 10)).padStart(2, "0")}`);
}
entries.sort();

const out = `/* Generated by scripts/build-concreteness.mjs — do not edit.
 * Source: Brysbaert, Warriner & Kuperman (2014), CC-BY 4.0. ${entries.length} lemmas, SUBTLEX ≥ ${minFreq}.
 * Format: "<word><score×10>" space-separated; score is mean concreteness on a 1–5 scale. */
export const CONCRETENESS_DATA = ${JSON.stringify(entries.join(" "))};
`;
writeFileSync("src/infrastructure/nlp/concreteness.data.ts", out);
console.log(`wrote ${entries.length} entries (${out.length} bytes)`);
